#ifndef AURORA_SHADER_H
#define AURORA_SHADER_H

static const char *vertex_shader_source =
    "#version 100\n"
    "attribute vec2 a_Position;\n"
    "varying vec2 v_TexCoord;\n"
    "void main() {\n"
    "    v_TexCoord = (a_Position + 1.0) * 0.5;\n"
    "    v_TexCoord.y = 1.0 - v_TexCoord.y;\n" // Invert Y for correct texture alignment
    "    gl_Position = vec4(a_Position, 0.0, 1.0);\n"
    "}\n";

static const char *vertex_shader_blit =
    "#version 100\n"
    "attribute vec2 a_Position;\n"
    "varying vec2 v_TexCoord;\n"
    "void main() {\n"
    "    v_TexCoord = (a_Position + 1.0) * 0.5;\n"
    "    gl_Position = vec4(a_Position, 0.0, 1.0);\n"
    "}\n";

static const char *fragment_shader_blit =
    "#version 100\n"
    "precision mediump float;\n"
    "varying vec2 v_TexCoord;\n"
    "uniform sampler2D u_Texture;\n"
    "void main() {\n"
    "    gl_FragColor = texture2D(u_Texture, v_TexCoord);\n"
    "}\n";

static const char *fragment_shader_lucy =
    "#version 100\n"
    "precision highp float;\n"
    "varying vec2 v_TexCoord;\n"
    "uniform sampler2D u_LucyTexture;\n"
    "uniform sampler2D u_MaskTexture;\n"
    "uniform float u_Time;\n"
    "\n"
    "float hash11(float p) {\n"
    "    p = fract(p * 0.1031);\n"
    "    p *= p + 33.33;\n"
    "    p *= p + p;\n"
    "    return fract(p);\n"
    "}\n"
    "\n"
    "float hash21(vec2 p) {\n"
    "    vec3 p3 = fract(vec3(p.xyx) * 0.1031);\n"
    "    p3 += dot(p3, p3.yzx + 33.33);\n"
    "    return fract((p3.x + p3.y) * p3.z);\n"
    "}\n"
    "\n"
    "bool isInsideSpan(float x, float xStart, float xWidth) {\n"
    "    float xEnd = xStart + xWidth;\n"
    "    return (x >= xStart && x <= xEnd) || (xEnd > 1.0 && x <= fract(xEnd));\n"
    "}\n"
    "\n"
    "float renderGlyph(vec2 cellUv, float seed) {\n"
    "    if (cellUv.x < 0.12 || cellUv.x > 0.88 || cellUv.y < 0.12 || cellUv.y > 0.88) return 0.0;\n"
    "    vec4 s4 = fract(seed * vec4(7.13, 13.37, 19.81, 29.43));\n"
    "    float p1 = step(0.35, s4.x) * (step(cellUv.x, 0.32) + step(0.68, cellUv.x));\n"
    "    float p2 = step(0.40, s4.y) * (step(cellUv.y, 0.32) + step(0.68, cellUv.y));\n"
    "    vec2 centerOffset = abs(cellUv - 0.5);\n"
    "    float p3 = step(0.30, s4.z) * step(centerOffset.x, 0.16);\n"
    "    float p4 = step(0.30, s4.w) * step(centerOffset.y, 0.16);\n"
    "    vec2 dCenter = cellUv - 0.5;\n"
    "    float centerDot = step(0.65, fract(seed * 43.19)) * step(dot(dCenter, dCenter), 0.0484);\n"
    "    return clamp(p1 + p2 + p3 + p4 + centerDot, 0.0, 1.0);\n"
    "}\n"
    "\n"
    "void main() {\n"
    "    vec2 uv = v_TexCoord;\n"
    "\n"
    "    // 1. Relic Glitch Displacement (Snappy double-pulse every 3.8s)\n"
    "    float time = u_Time * 1.5;\n"
    "    float cycle = mod(time, 3.8);\n"
    "    float tick1 = step(3.20, cycle) * (1.0 - step(3.30, cycle));\n"
    "    float tick2 = step(3.35, cycle) * (1.0 - step(3.43, cycle)) * 0.70;\n"
    "    float twitch = step(0.982, hash11(floor(time * 10.0))) * 0.45;\n"
    "    float glitchIntensity = max(max(tick1, tick2), twitch);\n"
    "\n"
    "    vec2 glitchUV = uv;\n"
    "    if (glitchIntensity > 0.005) {\n"
    "        float frameSeed = floor(time * 20.0) * 23.41;\n"
    "        float macroY = uv.y * 14.4;\n"
    "        float macroIndex = floor(macroY);\n"
    "        float macroSeed = macroIndex + frameSeed;\n"
    "        float macroHeight = hash11(macroSeed * 3.77) * 25.0 + 50.0;\n"
    "        float localY = fract(macroY) * 75.0;\n"
    "\n"
    "        if (hash11(macroSeed) > 0.65 && localY <= macroHeight) {\n"
    "            float xStart = hash11(macroSeed * 2.17);\n"
    "            float xWidth = hash11(macroSeed * 5.43) * 0.25 + 0.25;\n"
    "            if (isInsideSpan(uv.x, xStart, xWidth)) {\n"
    "                glitchUV.x += (hash11(macroSeed * 9.13) - 0.5) * 0.075 * glitchIntensity;\n"
    "            }\n"
    "        }\n"
    "    }\n"
    "\n"
    "    // 2. Authentic Wallpaper Engine Motions (FlowMap Breathing + Hair Waterwaves)\n"
    "    vec4 maskSample = texture2D(u_MaskTexture, glitchUV);\n"
    "\n"
    "    // A. FlowMap Breathing (shake.frag - id: 711)\n"
    "    vec2 flowMask = (vec2(maskSample.b, maskSample.g) - vec2(0.498, 0.498)) * 2.0;\n"
    "    float breathOffset = sin(u_Time * 1.0) * 0.01;\n"
    "    vec2 breathDisp = flowMask * breathOffset;\n"
    "\n"
    "    // B. Hair Waterwaves (waterwaves.frag - id: 141)\n"
    "    float waveDist = u_Time * 3.21 + glitchUV.y * 12.83;\n"
    "    float waveVal = sin(waveDist);\n"
    "    float hairWave = sign(waveVal) * pow(abs(waveVal), 1.08);\n"
    "    float hairDispX = hairWave * 0.0028 * maskSample.a;\n"
    "\n"
    "    vec2 lucyUV = glitchUV + breathDisp + vec2(hairDispX, 0.0);\n"
    "\n"
    "    vec4 lucyColor = texture2D(u_LucyTexture, lucyUV);\n"
    "    float bgMask = texture2D(u_MaskTexture, lucyUV).r;\n"
    "\n"
    "    // Fast-path GPU: le premier plan Lucy couvre ~65% de l'ecran\n"
    "    if (bgMask <= 0.001) {\n"
    "        gl_FragColor = lucyColor;\n"
    "        return;\n"
    "    }\n"
    "\n"
    "    // 3. Blackwall Cyber Grid & Deep Obsidian Void\n"
    "    vec3 bgVoid = mix(vec3(0.012, 0.001, 0.004), vec3(0.065, 0.002, 0.015), 1.0 - glitchUV.y);\n"
    "    float breath = sin(u_Time * 1.6) * 0.5 + 0.5;\n"
    "    float pulse = sin(u_Time * 0.9 - glitchUV.y * 3.5) * 0.5 + 0.5;\n"
    "    bgVoid += vec3(0.035, 0.001, 0.008) * (breath * 0.6 + pulse * 0.4);\n"
    "\n"
    "    vec2 gridCount = vec2(70.0, 40.0);\n"
    "    vec2 gridUv = glitchUV * gridCount;\n"
    "    vec2 gridFract = fract(gridUv);\n"
    "    float gridLine = max(step(0.92, gridFract.x), step(0.92, gridFract.y));\n"
    "    float gridWave = sin(gridUv.y * 0.25 - u_Time * 2.5) * 0.5 + 0.5;\n"
    "    vec3 gridColor = vec3(0.25, 0.008, 0.04) * gridLine * (0.30 + 0.70 * gridWave);\n"
    "\n"
    "    // 4. Data Streams Layer A (Micro Streams)\n"
    "    float colsA = 110.0;\n"
    "    float colIdA = floor(glitchUV.x * colsA);\n"
    "    float colU_A = fract(glitchUV.x * colsA);\n"
    "    float seedA = hash11(colIdA * 17.41);\n"
    "    float speedA = mix(0.5, 1.6, seedA);\n"
    "    float yFlowA = glitchUV.y + u_Time * speedA * 0.3 + seedA * 12.0;\n"
    "    float cellV_A = fract(yFlowA * 55.0);\n"
    "    float glyphA = renderGlyph(vec2(colU_A, cellV_A), hash21(vec2(colIdA, floor(yFlowA * 55.0))));\n"
    "    float phaseA = fract(yFlowA * 0.09 + seedA * 2.0);\n"
    "    float streamA = pow(max(0.0, 1.0 - phaseA), 3.0) * glyphA * 0.9;\n"
    "    vec3 colorA = vec3(0.40, 0.004, 0.06) * streamA;\n"
    "\n"
    "    // 5. Data Streams Layer B (Primary Cyber Streams + Cyan Sparks)\n"
    "    float colsB = 65.0;\n"
    "    float colIdB = floor(glitchUV.x * colsB);\n"
    "    float colU_B = fract(glitchUV.x * colsB);\n"
    "    float seedB = hash11(colIdB * 31.89);\n"
    "    float speedB = mix(0.4, 1.2, seedB);\n"
    "    float jitterTrig = step(0.982, hash11(floor(u_Time * 14.0) + colIdB));\n"
    "    float jitter = jitterTrig * (hash11(u_Time * 2.0 + colIdB) - 0.5) * 0.18;\n"
    "    float yFlowB = glitchUV.y + u_Time * speedB * 0.38 + seedB * 7.0 + jitter;\n"
    "    float cellV_B = fract(yFlowB * 38.0);\n"
    "    float glyphB = renderGlyph(vec2(colU_B, cellV_B), hash21(vec2(colIdB, floor(yFlowB * 38.0))));\n"
    "    float phaseB = fract(yFlowB * 0.13 + seedB * 5.0);\n"
    "    float tailB = pow(max(0.0, 1.0 - phaseB), 4.0);\n"
    "    float headB = smoothstep(0.95, 1.0, 1.0 - phaseB);\n"
    "    vec3 coreColor = vec3(0.65, 0.01, 0.12) * (glyphB * tailB * 1.6);\n"
    "    float isCyan = step(0.85, seedB);\n"
    "    vec3 sparkColor = mix(vec3(0.85, 0.15, 0.25), vec3(0.0, 0.95, 1.0), isCyan);\n"
    "    vec3 colorB = coreColor + sparkColor * (glyphB * headB * 2.0);\n"
    "\n"
    "    // 6. Subtractive Scanlines & Contrast\n"
    "    float scanline = 1.0 - ((sin(glitchUV.y * 540.0) * 0.5 + 0.5) * 0.08);\n"
    "    vec3 blackwallBg = (bgVoid + gridColor + colorA + colorB) * scanline;\n"
    "\n"
    "    // 7. Composite\n"
    "    vec3 finalRgb = mix(lucyColor.rgb, blackwallBg, bgMask);\n"
    "    gl_FragColor = vec4(finalRgb, 1.0);\n"
    "}\n";

#endif // AURORA_SHADER_H
